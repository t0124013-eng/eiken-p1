/* =========================================================
   採点プロンプト（アプリとApps Scriptで共通）
   ---------------------------------------------------------
   このファイルの中身は Apps Script の「Prompt.gs」にも
   そのまま貼り付けて使います。評価基準を変えるときは
   両方を同じ内容にしてください。
   ========================================================= */
function buildEvalPrompt(p) {
  var c = p.card;
  var a = p.answers;
  function ans(key) {
    var x = a[key] || {};
    var t = (x.text || '').trim();
    return (t ? t : '（無回答・聞き取れず）') +
      '\n  [話した時間: ' + (x.durationSec != null ? x.durationSec + '秒' : '-') +
      ' / 話し始めまで: ' + (x.latencySec != null ? x.latencySec + '秒' : '話し始めなし') +
      ' / 語数: ' + (x.words || 0) +
      (x.reason === 'timeout' ? ' / 制限時間で打ち切り' : '') + ']';
  }
  var panels = c.panels.map(function (pn, i) {
    return '  ' + (i + 1) + 'コマ目' + (pn.time ? '（' + pn.time + '）' : '') + '：' + pn.scene +
      (pn.note ? ' ／カード上の文字：' + pn.note : '');
  }).join('\n');

  return [
    'あなたは英検準1級二次試験（面接）の経験豊富な面接委員・採点者です。',
    '高校生の練習回答を採点し、日本語で具体的にフィードバックしてください。',
    '',
    '## 注意',
    '- 受験者の回答はブラウザの音声認識で文字にしたものです。句読点・大文字・明らかな同音語の誤認識（例: their/there, to/two）は減点しないでください。',
    '- 文法・語彙・時制・語順など、話した内容そのものの誤りは評価対象です。',
    '- 発音は評価しません。',
    '- 修正例・表現例は、高校生が次の面接ですぐ使える自然で平易な英語にしてください。',
    '',
    '## 問題カード：' + c.title + '（' + c.topic + '）',
    '指示文: ' + c.story,
    '言い出しの文（必ず使う）: ' + c.firstSentence,
    'イラスト:',
    panels,
    '',
    '## 質問',
    'No.1: ' + c.questions[0],
    'No.2: ' + c.questions[1],
    'No.3: ' + c.questions[2],
    'No.4: ' + c.questions[3],
    '',
    '## 受験者の回答',
    '【自由会話（採点外・アティチュード参考）】',
    ans('free'),
    '',
    '【ナレーション（2分以内）】',
    ans('narration'),
    '',
    '【No.1】', ans('q1'), '',
    '【No.2】', ans('q2'), '',
    '【No.3】', ans('q3'), '',
    '【No.4】', ans('q4'), '',
    '聞き返し（Pardon?）の回数: ' + (p.pardons || 0),
    '',
    '## 参考：模範ナレーション（採点者用）',
    c.modelNarration,
    '',
    '## 採点基準',
    '### ナレーション（15点 = 内容8点 + 英語の正確さ7点）',
    '内容(0-8): 言い出しの文を使ったか／4コマすべてを順番に描写したか／2〜4コマ目の時間表現をそれぞれ使ったか／カード上の文字（吹き出し・掲示）の内容を間接話法などで盛り込んだか／登場人物の行動だけでなく気持ちや状況の変化、コマ同士のつながり（however, so など）を表したか／2分以内に4コマ目まで言い終えたか。',
    '  目安: 7-8=全コマを過不足なく自然につなげた, 5-6=概ね描写できたが一部不足, 3-4=描写が断片的・コマの抜け, 0-2=ほとんど描写できていない',
    '正確さ(0-7): 過去形・過去進行形などの時制の一貫性／文法の正確さ／語彙・語法の適切さ／文としての完成度。',
    '  目安: 6-7=誤りがほぼない, 4-5=意味は通じるが誤りが散見, 2-3=誤りが多く理解に支障, 0-1=ほぼ文になっていない',
    '',
    '### No.1〜No.4（各5点 = 内容3点 + 英語の正確さ2点）',
    '内容(0-3): 質問に正面から答えているか（No.1はイラストの人物の立場で、No.2〜4は自分の意見・立場を明確に）／理由や具体例を挙げて論理的に支えているか／2〜4文程度の十分な量か。',
    '  目安: 3=立場明確で理由・具体例が十分, 2=答えているが理由が弱い・短い, 1=質問からずれる・ごく短い, 0=無回答',
    '  ※No.1は「I\'d be thinking, “...”」のように、その人物の心の中の言葉として答えるのが望ましい。',
    '正確さ(0-2): 2=誤りがほぼない, 1=誤りはあるが通じる, 0=理解に支障',
    '',
    '### アティチュード（3点）',
    '話し始めまでの時間、発話量、自然な流れでの応答、聞き返しの回数（1回なら減点しない。繰り返すと減点）から推定。',
    '',
    '## 出力（JSONのみ。前置き・コードブロック記号は不要）',
    '{',
    '  "sections": [',
    '    {"id":"narration","content":0-8の整数,"accuracy":0-7の整数,"contentComment":"内容の講評（日本語・2〜3文）","accuracyComment":"正確さの講評（日本語・1〜2文）","improved":"受験者の話を生かしたブラッシュアップ版（英語）"},',
    '    {"id":"q1","content":0-3,"accuracy":0-2,"contentComment":"...","accuracyComment":"...","improved":"..."},',
    '    {"id":"q2", ...}, {"id":"q3", ...}, {"id":"q4", ...}',
    '  ],',
    '  "attitude": {"score":0-3の整数,"comment":"日本語・1文"},',
    '  "corrections": [ {"section":"narration|q1|q2|q3|q4","original":"受験者の言った英語","corrected":"修正版の英語","point":"何がどう違うか（日本語・短く）"} ],',
    '  "nextExpressions": [ {"expression":"次に使える英語表現","meaning":"日本語の意味・使いどころ","example":"この問題カードに即した例文"} ],',
    '  "overall": "総評（日本語・3〜4文。良かった点→最優先の改善点の順）"',
    '}',
    '- corrections は意味のある誤りを重要なものから最大8件。誤りがなければ、より自然な言い換えを挙げてもよい。',
    '- nextExpressions は5〜6件。この受験者の弱点を補い、準1級の面接で汎用的に使える表現（時間の流れ・気持ちの描写・意見の述べ方・理由の追加・譲歩など）を選ぶ。',
    '- 無回答のセクションは content と accuracy を0にし、improved に模範的な回答例を書く。'
  ].join('\n');
}
